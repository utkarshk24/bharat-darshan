#!/usr/bin/env python3
"""
npm run fonts — subset the eight regional-script fonts to the characters the site actually uses.

Regional scripts (Bengali, Gurmukhi, Gujarati, Oriya, Tamil, Telugu, Kannada, Malayalam) appear
only in local names, a few dozen characters in all. The full Fontsource files are ~80-120 KB each
and the home page shows all eight, so they dominated mobile load time. The subsets keep every
OpenType layout feature (conjuncts and vowel signs shape correctly) and the weight axis.

Also copies the two core fonts (Inter, Noto Sans Devanagari) to public/fonts/ under fixed names,
so the layout can declare them with the site's base path and preload the one each page needs
(see src/lib/fonts.ts).

Writes:
  public/fonts/<core>.woff2               Inter + Noto Sans Devanagari (copied unchanged)
  src/app/fonts/regional/<script>.woff2   subset fonts
  src/app/fonts/regional.css              @font-face rules (imported by globals.css)
  src/app/fonts/regional-chars.json       characters covered, checked by tests/fonts.test.ts

Re-run whenever new regional-script text is added; the unit test fails until you do.
Needs: pip install fonttools brotli
"""
import glob
import json
import os
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "src", "app", "fonts")

# script key -> (Fontsource package/file stem, family name, Unicode block)
SCRIPTS = {
    "bengali": ("noto-sans-bengali", "bengali", "Noto Sans Bengali Variable", (0x0980, 0x09FF)),
    "gurmukhi": ("noto-sans-gurmukhi", "gurmukhi", "Noto Sans Gurmukhi Variable", (0x0A00, 0x0A7F)),
    "gujarati": ("noto-sans-gujarati", "gujarati", "Noto Sans Gujarati Variable", (0x0A80, 0x0AFF)),
    "oriya": ("noto-sans-oriya", "oriya", "Noto Sans Oriya Variable", (0x0B00, 0x0B7F)),
    "tamil": ("noto-sans-tamil", "tamil", "Noto Sans Tamil Variable", (0x0B80, 0x0BFF)),
    "telugu": ("noto-sans-telugu", "telugu", "Noto Sans Telugu Variable", (0x0C00, 0x0C7F)),
    "kannada": ("noto-sans-kannada", "kannada", "Noto Sans Kannada Variable", (0x0C80, 0x0CFF)),
    "malayalam": ("noto-sans-malayalam", "malayalam", "Noto Sans Malayalam Variable", (0x0D00, 0x0D7F)),
}
JOINERS = [0x200C, 0x200D]  # ZWNJ / ZWJ change shaping, so keep them with every script


def used_chars():
    """Every regional-script character in the dataset, UI strings and source code."""
    files = (
        glob.glob(os.path.join(ROOT, "data", "**", "*.json"), recursive=True)
        + glob.glob(os.path.join(ROOT, "messages", "*.json"))
        + glob.glob(os.path.join(ROOT, "src", "**", "*.ts"), recursive=True)
        + glob.glob(os.path.join(ROOT, "src", "**", "*.tsx"), recursive=True)
    )
    found = {k: set() for k in SCRIPTS}
    for f in files:
        with open(f, encoding="utf-8") as fh:
            text = fh.read()
        for ch in set(text):
            o = ord(ch)
            for k, (*_, (lo, hi)) in SCRIPTS.items():
                if lo <= o <= hi:
                    found[k].add(o)
    return found


# public/fonts/<name> ← Fontsource file. Names are referenced by src/lib/fonts.ts.
CORE = {
    "inter-latin.woff2": ("inter", "inter-latin-wght-normal.woff2"),
    "inter-latin-ext.woff2": ("inter", "inter-latin-ext-wght-normal.woff2"),
    "deva.woff2": ("noto-sans-devanagari", "noto-sans-devanagari-devanagari-wght-normal.woff2"),
    "deva-latin.woff2": ("noto-sans-devanagari", "noto-sans-devanagari-latin-wght-normal.woff2"),
    "deva-latin-ext.woff2": ("noto-sans-devanagari", "noto-sans-devanagari-latin-ext-wght-normal.woff2"),
}


def copy_core():
    import shutil
    dest = os.path.join(ROOT, "public", "fonts")
    os.makedirs(dest, exist_ok=True)
    for name, (pkg, f) in CORE.items():
        src = os.path.join(ROOT, "node_modules", "@fontsource-variable", pkg, "files", f)
        if not os.path.exists(src):
            sys.exit(f"fonts: missing {src} — run npm install")
        shutil.copyfile(src, os.path.join(dest, name))
    print(f"fonts: copied {len(CORE)} core fonts to public/fonts")


def main():
    copy_core()
    os.makedirs(os.path.join(OUT, "regional"), exist_ok=True)
    found = used_chars()
    css = [
        "/* Generated by scripts/fonts/subset_regional.py (npm run fonts). Do not edit by hand. */",
        "/* Regional-script fonts subset to the characters the site uses; full OpenType shaping kept. */",
    ]
    manifest = {}
    total = 0
    for key, (pkg, stem, family, (lo, hi)) in SCRIPTS.items():
        src = os.path.join(ROOT, "node_modules", "@fontsource-variable", pkg, "files", f"{pkg}-{stem}-wght-normal.woff2")
        if not os.path.exists(src):
            sys.exit(f"fonts: missing {src} — run npm install")
        cps = sorted(found[key])
        manifest[key] = "".join(chr(c) for c in cps)
        if not cps:
            continue
        opts = subset.Options()
        opts.flavor = "woff2"
        opts.layout_features = ["*"]  # keep every GSUB/GPOS feature: conjuncts, reph, matra positioning
        opts.name_IDs = ["*"]
        opts.notdef_outline = True
        opts.hinting = False
        font = TTFont(src)
        sub = subset.Subsetter(opts)
        sub.populate(unicodes=cps + JOINERS)
        sub.subset(font)
        dest = os.path.join(OUT, "regional", f"{key}.woff2")
        font.flavor = "woff2"
        font.save(dest)
        size = os.path.getsize(dest)
        total += size
        css.append(
            "@font-face{"
            f'font-family:"{family}";font-style:normal;font-display:swap;font-weight:100 900;'
            f'src:url(./regional/{key}.woff2) format("woff2-variations");'
            f"unicode-range:U+{lo:04X}-{hi:04X},U+200C-200D"
            "}"
        )
        print(f"fonts: {key:<10} {len(cps):>3} chars → {size / 1024:.1f} KB")
    with open(os.path.join(OUT, "regional.css"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(css) + "\n")
    with open(os.path.join(OUT, "regional-chars.json"), "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, ensure_ascii=False, indent=2)
        fh.write("\n")
    print(f"fonts: {total / 1024:.1f} KB total for 8 regional scripts")


if __name__ == "__main__":
    main()
