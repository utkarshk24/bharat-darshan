/**
 * npm run validate-data           — schema + content checks, writes docs/DATA-GAP-REPORT.md
 * npm run validate-data:links     — also checks that every source URL resolves
 * Exit code 1 if any error is found.
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { validateDataset, collectUrls, type Finding, type RawFiles } from "../src/lib/validate";

const root = path.resolve(import.meta.dirname, "..");
const read = (p: string) => JSON.parse(readFileSync(path.join(root, p), "utf8"));

const regionFiles = readdirSync(path.join(root, "data/regions")).filter((f) => f.endsWith(".json")).sort();
const raw: RawFiles = {
  india: { file: "india.json", json: read("data/india.json") },
  regions: regionFiles.map((f) => ({ file: `regions/${f}`, json: read(`data/regions/${f}`) })),
  sources: read("data/sources.json"),
  glossary: read("data/glossary.json"),
  modules: existsSync(path.join(root, "data/modules"))
    ? readdirSync(path.join(root, "data/modules")).flatMap((code) =>
        readdirSync(path.join(root, "data/modules", code))
          .filter((f) => f.endsWith(".json"))
          .map((f) => ({ file: `modules/${code}/${f}`, json: read(`data/modules/${code}/${f}`) })),
      )
    : [],
  compare: existsSync(path.join(root, "data/compare/indicators.json")) ? read("data/compare/indicators.json") : undefined,
  mapManifest: existsSync(path.join(root, "public/maps/manifest.json")) ? read("public/maps/manifest.json") : undefined,
};

async function checkLinks(urls: string[]): Promise<Finding[]> {
  const out: Finding[] = [];
  await Promise.all(
    urls.map(async (u) => {
      try {
        const ctrl = AbortSignal.timeout(15000);
        let res = await fetch(u, { method: "HEAD", redirect: "follow", signal: ctrl });
        if (res.status === 405 || res.status === 403) res = await fetch(u, { method: "GET", redirect: "follow", signal: AbortSignal.timeout(15000) });
        if (!res.ok) out.push({ severity: "warning", file: "links", path: u, message: `HTTP ${res.status}` });
      } catch (e) {
        out.push({ severity: "warning", file: "links", path: u, message: `unreachable (${(e as Error).message})` });
      }
    }),
  );
  return out;
}

const findings = validateDataset(raw);
if (process.argv.includes("--check-links")) findings.push(...(await checkLinks(collectUrls(raw))));

const by = (s: Finding["severity"]) => findings.filter((f) => f.severity === s);
const errors = by("error"), warnings = by("warning"), gaps = by("gap");

const fmt = (f: Finding) => `- \`${f.file}\` ${f.path ? `\`${f.path}\`` : ""} — ${f.message}`;
const groupByFile = (list: Finding[]) => {
  const m = new Map<string, Finding[]>();
  for (const f of list) m.set(f.file, [...(m.get(f.file) ?? []), f]);
  return m;
};

let md = `# Data-gap & validation report\n\nGenerated by \`npm run validate-data\` on ${new Date().toISOString().slice(0, 10)}.\n\n`;
md += `| Errors | Warnings | Gaps (TODO values) | Region files |\n|---|---|---|---|\n| ${errors.length} | ${warnings.length} | ${gaps.length} | ${regionFiles.length + 1} |\n\n`;
if (errors.length) md += `## Errors\n\n${errors.map(fmt).join("\n")}\n\n`;
md += `## Warnings\n\n${warnings.length ? warnings.map(fmt).join("\n") : "None."}\n\n`;
md += `## Gaps by file\n\n`;
for (const [file, list] of groupByFile(gaps)) {
  md += `<details><summary><code>${file}</code> — ${list.length} TODO</summary>\n\n${list.map((f) => `- \`${f.path}\` — ${f.message}`).join("\n")}\n\n</details>\n\n`;
}
writeFileSync(path.join(root, "docs/DATA-GAP-REPORT.md"), md);

console.log(`validate-data: ${errors.length} error(s), ${warnings.length} warning(s), ${gaps.length} gap(s) across ${regionFiles.length + 1} region files`);
for (const f of errors) console.error("  ERROR " + fmt(f).slice(2));
for (const f of warnings.slice(0, 20)) console.warn("  warn  " + fmt(f).slice(2));
if (warnings.length > 20) console.warn(`  … ${warnings.length - 20} more warnings in docs/DATA-GAP-REPORT.md`);
console.log("  report → docs/DATA-GAP-REPORT.md");
process.exit(errors.length ? 1 : 0);
